"""docs/openapi.json is the API contract, and it must be the one the code has.

The schema is not served at runtime; it is generated by core.openapi_export
and committed, so every change to a request or response shape shows up as a
diff in review. These tests keep that file honest and keep every JSON route
inside it.
"""

from __future__ import annotations

import unittest

from fastapi import FastAPI
from fastapi.testclient import TestClient

from core.admin_routes import register_admin_routes
from core.openapi_export import SCHEMA_PATH, render
from core.routes.common import STATIC_DIR
from core.web_server import app

# Serves a file, not JSON, so it has no response model to describe.
_FILE_ROUTES = {("get", "/api/log-images/{image_name}")}


class TestTheContract(unittest.TestCase):
    def test_committed_schema_is_fresh(self) -> None:
        # read_text() normalises newlines, so a CRLF checkout still compares.
        self.assertEqual(
            SCHEMA_PATH.read_text(encoding="utf-8"),
            render(),
            "docs/openapi.json is stale: run `python -m core.openapi_export` "
            "and commit it",
        )

    def test_every_api_route_has_a_response_schema(self) -> None:
        missing: list[str] = []
        for path, operations in app.openapi()["paths"].items():
            if not path.startswith("/api/"):
                continue
            for method, operation in operations.items():
                if (method, path) in _FILE_ROUTES:
                    continue
                content = operation["responses"]["200"].get("content", {})
                schema = content.get("application/json", {}).get("schema", {})
                if "$ref" not in schema:
                    missing.append(f"{method.upper()} {path}")
        self.assertEqual(missing, [], "routes without a response_model")

    def test_admin_route_is_not_in_the_schema(self) -> None:
        """Otherwise the schema would depend on the generating machine's env."""
        admin_app = FastAPI()
        register_admin_routes(admin_app, str(STATIC_DIR))
        self.assertNotIn("/api/admin/stats", admin_app.openapi()["paths"])


class TestNothingIsServedAtRuntime(unittest.TestCase):
    def test_runtime_docs_are_closed(self) -> None:
        client = TestClient(app)
        for path in ("/openapi.json", "/docs", "/redoc"):
            with self.subTest(path=path):
                self.assertEqual(client.get(path).status_code, 404)


if __name__ == "__main__":
    unittest.main()
